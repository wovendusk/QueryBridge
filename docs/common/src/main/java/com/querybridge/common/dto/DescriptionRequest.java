package com.querybridge.common.dto;   // the shared DTO package (see QueryHistory.java)

import java.util.List;                 // we carry lists of column names/types/rows

// ============================================================================
// DescriptionRequest — "LLM, please explain what each column of this table
// means." (guide step 4)
//
// DIRECTION:  CLI  ──(Kafka topic "description.request")──▶  LLM service
// ANSWERED BY: DescriptionResponse on topic "description.response"
//
// THE BIG IDEA BEHIND THIS MESSAGE
//   Real databases often have cryptic column names: `col_nm`, `amt_2`,
//   `vl_cnt`. If a user later asks "how many villagers are there?", an LLM
//   that only sees `vl_cnt (integer)` might not realise that's the column.
//
//   So right after you `connect`, the CLI loops over EVERY table, grabs the
//   column names, the column types and up to 10 sample rows, and sends one
//   DescriptionRequest PER TABLE. The LLM looks at the sample values and
//   writes a human description for each column ("Number of villagers in the
//   settlement"). Those descriptions are then pasted into every later SQL
//   generation prompt as part of the schema text. Better context in → better
//   SQL out.
//
// THE CORRELATION ID — THE MOST IMPORTANT FIELD IN EVERY MESSAGE
//   Kafka is not HTTP. When you send a message on a topic, there is no
//   built-in "reply" to that specific message. The LLM service will
//   eventually publish SOME message on "description.response", but how does
//   the CLI know which response belongs to which request?
//
//   Answer: the CLI invents a random UUID (the correlationId), puts it in the
//   request, and the LLM service copies the same ID into its response. The
//   CLI keeps a map  correlationId -> "the code waiting for this answer", and
//   when a response arrives, it looks up the ID and wakes that code up.
//   This is the classic "request-reply over a message bus" pattern; you will
//   see it implemented in cli-app/kafka/KafkaProducerService.java.
//
//   Every request/response DTO in this package has a correlationId for this
//   reason (only QueryHistory doesn't, because it's never sent on its own).
//
// EXAMPLE JSON (what actually travels over Kafka):
//   {
//     "correlationId": "3f1c...e9",
//     "tableName": "products",
//     "columnNames": ["id", "name", "price"],
//     "columnTypes": ["integer", "text", "numeric"],
//     "sampleRows": [["1", "Lamp", "19.99"], ["2", "Desk", "120.00"]]
//   }
// ============================================================================
public class DescriptionRequest {
    // Random UUID string generated by the CLI; echoed back in the response.
    private String correlationId;
    // The table we want described, e.g. "products".
    private String tableName;
    // Column names in table order, e.g. ["id", "name", "price"].
    private List<String> columnNames;
    // Column types in THE SAME ORDER as columnNames (index i of one list
    // matches index i of the other), e.g. ["integer", "text", "numeric"].
    // These are PostgreSQL's information_schema "data_type" strings.
    private List<String> columnTypes;
    // Up to 10 rows of real data. Outer list = rows; inner list = the values of
    // one row, again in column order. EVERYTHING is a String (numbers, dates,
    // booleans were all converted with toString(); SQL NULL became the text
    // "NULL"). Strings keep the JSON simple — the LLM only needs to READ them.
    private List<List<String>> sampleRows;

    // No-arg constructor: needed by Jackson to deserialize the JSON on the
    // LLM-service side (see the long explanation in QueryHistory.java).
    public DescriptionRequest() {}

    // All-fields constructor: used by the CLI (QueryBridgeCommands.connect)
    // to build the request in one go.
    public DescriptionRequest(String correlationId, String tableName,
                              List<String> columnNames, List<String> columnTypes,
                              List<List<String>> sampleRows) {
        this.correlationId = correlationId;   // the reply-matching ID
        this.tableName = tableName;           // which table
        this.columnNames = columnNames;       // its columns...
        this.columnTypes = columnTypes;       // ...their types...
        this.sampleRows = sampleRows;         // ...and some real data
    }

    // Standard getters/setters. Jackson uses the getters to WRITE JSON (on the
    // CLI side) and the setters to READ JSON (on the LLM-service side).
    public String getCorrelationId() { return correlationId; }
    public void setCorrelationId(String correlationId) { this.correlationId = correlationId; }
    public String getTableName() { return tableName; }
    public void setTableName(String tableName) { this.tableName = tableName; }
    public List<String> getColumnNames() { return columnNames; }
    public void setColumnNames(List<String> columnNames) { this.columnNames = columnNames; }
    public List<String> getColumnTypes() { return columnTypes; }
    public void setColumnTypes(List<String> columnTypes) { this.columnTypes = columnTypes; }
    public List<List<String>> getSampleRows() { return sampleRows; }
    public void setSampleRows(List<List<String>> sampleRows) { this.sampleRows = sampleRows; }
}
